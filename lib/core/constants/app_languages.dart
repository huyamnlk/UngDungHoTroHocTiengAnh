class AppLanguageItem {
  final String code;
  final String flag;
  final String nativeName;
  final String viName;
  final String englishName;
  final Map<String, String> localizedNames;

  const AppLanguageItem({
    required this.code,
    required this.flag,
    required this.nativeName,
    required this.viName,
    required this.englishName,
    required this.localizedNames,
  });

  String getSubtitle(String activeLocaleCode) {
    final normalized = activeLocaleCode.trim().toLowerCase();
    if (code == 'vi') {
      return AppLanguages.defaultBadges[normalized] ??
          localizedNames[normalized] ??
          nativeName;
    }
    if (normalized == 'vi') return viName;
    if (normalized == 'en') return englishName;
    return localizedNames[normalized] ?? nativeName;
  }
}

